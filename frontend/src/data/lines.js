export function getLineBySlug(slug, source = lines) {
  return source.find((item) => item.slug === slug || item.code === slug);
}

export function normalizeLineFromApi(item) {
  const slug =
    item.slug || item.lineSlug || item.lineCode || item.code || item.name;
  return {
    ...item,
    slug,
    code: item.code || item.lineCode || slug,
    name: item.name || item.lineName || slug,
    displayName: item.displayName || item.lineName || item.name || slug,
    ipAddress: item.ipAddress || item.ip || "",
    plcBrand: item.plcBrand || item.plc || "Omron",
    displayOrder: item.displayOrder ?? item.order ?? 1,
    isActive: item.isActive ?? item.active ?? true,
  };
}
